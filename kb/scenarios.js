/** 敏感信息脱敏：把疑似真实卡号/手机号/链接替换为占位符（纯函数，D8） */
export const PLACEHOLDER_CARD = '［卡号已脱敏］';
export const PLACEHOLDER_PHONE = '［手机号已脱敏］';
export const PLACEHOLDER_URL = '［链接已屏蔽］';

const RE_CARD = /\b\d[\d\s-]{13,21}\d\b/g;
const RE_PHONE = /\b1[3-9]\d{9}\b/g;
const RE_URL = /\b(?:https?:\/\/|www\.)[^\s，。！？]+/gi;

/** @param {string} text @returns {string} */
export function sanitize(text) {
  if (typeof text !== 'string') return '';
  return text
    .replace(RE_CARD, PLACEHOLDER_CARD)
    .replace(RE_PHONE, PLACEHOLDER_PHONE)
    .replace(RE_URL, PLACEHOLDER_URL);
}

