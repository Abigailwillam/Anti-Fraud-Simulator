/** 分类 id → 案例 id 列表（预建索引，分类切换零遍历） */
export const CATEGORY_INDEX = CASE_CATEGORIES.reduce((idx, c) => {
  idx[c.id] = Object.values(CASES).filter((x) => x.catId === c.id).map((x) => x.id);
  return idx;
}, {});

/** @param {string} id @returns {any|null} */
export function getCase(id) {
  return CASES[id] || null;
}

/** @param {string} catId @returns {any[]} */
export function casesOfCategory(catId) {
  return (CATEGORY_INDEX[catId] || []).map((id) => CASES[id]);
}

/** @param {string} catId @returns {any|null} */
export function getCategory(catId) {
  return CASE_CATEGORIES.find((c) => c.id === catId) || null;
}